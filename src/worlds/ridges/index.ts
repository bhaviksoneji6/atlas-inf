/**
 * Ink Ridges — scroll, SVG.
 *
 * The second world exists to exercise the other half of the engine: the 1-D
 * strip cache, the SVG renderer, and the ported brush doing what it was
 * actually designed for. The receding washes are a nod to upstream's distant
 * mountains; the composition is original, and far simpler than Lingdong's.
 */

import type { GenContext, Polyline, Pt, World } from '../../engine/types';

const BAND = 800;

interface Layer {
  /** Horizon height as a fraction of the band. */
  base: number;
  amp: number;
  freq: number;
  wash: string;
  edge: string;
  /** Trees per tile; 0 for the distant layers. */
  trees: number;
}

/**
 * Opaque washes, not translucent ones.
 *
 * These were originally rgba with alpha, which looked right in isolation and
 * produced vertical bands in situ: tiles overlap by a pad so ridgelines cross
 * the seam continuously, and in the overlap every translucent fill composited
 * twice. Opaque colours chosen to match what the alpha stack used to resolve
 * to make the overlap invisible — the far layers are already lightened here
 * rather than relying on the paper showing through.
 */
const LAYERS: Layer[] = [
  { base: 0.30, amp: 128, freq: 0.0052, wash: '#d9d8cc', edge: '#9aa6ab', trees: 0 },
  { base: 0.44, amp: 150, freq: 0.0074, wash: '#c4c7bf', edge: '#808f97', trees: 0 },
  { base: 0.60, amp: 164, freq: 0.0104, wash: '#a8b0ad', edge: '#5f7380', trees: 4 },
  { base: 0.78, amp: 140, freq: 0.0152, wash: '#7f8c90', edge: '#3d5261', trees: 8 },
  { base: 0.98, amp: 104, freq: 0.0223, wash: '#55656e', edge: '#1f3040', trees: 12 },
];

export const ridgesWorld: World = {
  id: 'ridges',
  name: 'Ink Ridges',
  blurb:
    'Receding ridgelines in ink wash, scrolling sideways forever. The brush primitives from shan-shui-inf, doing what they were built for.',
  mode: 'scroll',
  renderer: 'svg',
  background: '#efe9dc',
  ink: '#1a2632',
  tileSize: 512,
  bandHeight: BAND,
  initialScale: 1,

  generate(ctx: GenContext): Polyline[] {
    const out: Polyline[] = [];
    const stepX = Math.max(4, 10 / ctx.detail);
    const pad = stepX * 2;

    LAYERS.forEach((layer, li) => {
      const baseY = BAND * layer.base;

      // Sample on a global lattice rather than from the tile's own left edge.
      // Adjacent tiles then evaluate the ridge at *identical* x values, so the
      // shared points coincide exactly and the overlap region draws the same
      // geometry twice instead of two slightly offset versions of it.
      const ridge: Pt[] = [];
      const xStart = Math.floor((ctx.x - pad) / stepX) * stepX;
      const xEnd = Math.ceil((ctx.x + ctx.w + pad) / stepX) * stepX;
      for (let x = xStart; x <= xEnd; x += stepX) {
        const n = ctx.noise.fbm(x * layer.freq, li * 13.7, 5);
        const r = ctx.noise.ridged(x * layer.freq * 2.1, li * 5.3, 4);
        ridge.push([x, baseY - (n * 0.72 + r * 0.28) * layer.amp]);
      }

      // Wash: the ridge closed down to the foot of the band.
      const skirt: Pt[] = [
        ...ridge,
        [ridge[ridge.length - 1]![0], BAND + 40],
        [ridge[0]![0], BAND + 40],
        ridge[0]!,
      ];
      out.push({ pts: skirt, fill: layer.wash, stroke: 'none', width: 0, z: li * 10 });

      // Inked crest.
      out.push(
        ctx.brush.stroke(ridge, {
          col: layer.edge,
          wid: 1.6 + li * 0.5,
          noi: 0.45,
          out: 0,
          z: li * 10 + 1,
          fun: (t) => Math.sin(t * Math.PI) ** 0.35,
        }),
      );

      if (layer.trees === 0) return;

      // Planner pattern, upstream's `mountplanner` in miniature: local maxima
      // of a density field become sites, with a minimum-distance rejection so
      // the trees group rather than spread evenly.
      const sites: number[] = [];
      const probe = 6;
      // Period of the density field, ~50 world units. At the original 0.004 it
      // was ~250, which meant a 512-wide tile contained one or two maxima in
      // total and the "forest" came out as a couple of lonely trees.
      const densityFreq = 0.02;
      const minDist = 30 - li * 3;
      const want = Math.round(layer.trees * ctx.detail);

      // Lattice-aligned and clipped to the tile, so a tree near a seam is
      // generated by exactly one of the two tiles rather than by both at
      // marginally different positions.
      const t0 = Math.ceil(ctx.x / probe) * probe;
      for (let x = t0; x < ctx.x + ctx.w && sites.length < want; x += probe) {
        const d0 = ctx.noise.noise2(x * densityFreq, 50 + li);
        if (d0 < 0.44) continue;
        if (
          ctx.noise.noise2((x - probe) * densityFreq, 50 + li) > d0 ||
          ctx.noise.noise2((x + probe) * densityFreq, 50 + li) > d0
        ) {
          continue;
        }
        if (sites.some((s) => Math.abs(s - x) < minDist)) continue;
        sites.push(x);

        const rng = ctx.rngAt(x, li);
        const n = ctx.noise.fbm(x * layer.freq, li * 13.7, 5);
        const r = ctx.noise.ridged(x * layer.freq * 2.1, li * 5.3, 4);
        const groundY = baseY - (n * 0.72 + r * 0.28) * layer.amp;

        const height = (20 + rng() * 26) * (0.55 + li * 0.3);
        const trunk: Pt[] = [
          [x, groundY],
          [x + rng.range(-2, 2), groundY - height * 0.55],
          [x + rng.range(-3, 3), groundY - height],
        ];
        out.push(
          ctx.brush.stroke(ctx.brush.div(trunk, 6), {
            col: layer.edge,
            wid: 1.1 + li * 0.25,
            noi: 0.6,
            out: 0,
            z: li * 10 + 2,
            fun: (t) => 1 - t * 0.8,
          }),
        );

        // A cluster of small blobs reads as foliage; two big ones read as a
        // mushroom. Spread them up the top third of the trunk and keep each
        // one well under the tree's height.
        const canopy = 5 + rng.int(5);
        for (let c = 0; c < canopy; c++) {
          const t = c / canopy;
          out.push(
            ctx.brush.blob(
              x + rng.range(-height * 0.26, height * 0.26),
              groundY - height * (0.72 + t * 0.32) - rng.range(0, height * 0.1),
              {
                len: height * rng.range(0.22, 0.4),
                wid: height * rng.range(0.14, 0.24),
                ang: rng.range(-0.5, 0.5),
                col: layer.edge,
                noi: 0.8,
                z: li * 10 + 3,
              },
            ),
          );
        }
      }
    });

    return out;
  },
};
